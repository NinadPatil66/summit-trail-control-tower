-- 01_warehouses.sql: compute. Safe to rerun.
-- Pattern: CREATE ... IF NOT EXISTS, then ALTER to enforce the settings.
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS load_wh WITH WAREHOUSE_SIZE = XSMALL INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE load_wh SET WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800 COMMENT = 'COPY, Snowpipe tests, unloads';

CREATE WAREHOUSE IF NOT EXISTS transform_wh WITH WAREHOUSE_SIZE = XSMALL INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE transform_wh SET WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800 COMMENT = 'dbt runs';

CREATE WAREHOUSE IF NOT EXISTS bi_wh WITH WAREHOUSE_SIZE = XSMALL INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE bi_wh SET WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800 COMMENT = 'Ad hoc queries and the Streamlit app';

CREATE WAREHOUSE IF NOT EXISTS ai_wh WITH WAREHOUSE_SIZE = XSMALL INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE ai_wh SET WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800 COMMENT = 'Cortex and Snowpark ML';

-- Daily caps. Only ACCOUNTADMIN can create monitors and attach them.
USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS rm_load_daily WITH CREDIT_QUOTA = 4
  FREQUENCY = DAILY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 90 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
CREATE RESOURCE MONITOR IF NOT EXISTS rm_transform_daily WITH CREDIT_QUOTA = 6
  FREQUENCY = DAILY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 90 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
CREATE RESOURCE MONITOR IF NOT EXISTS rm_bi_daily WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 90 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
CREATE RESOURCE MONITOR IF NOT EXISTS rm_ai_daily WITH CREDIT_QUOTA = 4
  FREQUENCY = DAILY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 90 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER RESOURCE MONITOR rm_load_daily SET CREDIT_QUOTA = 4;
ALTER RESOURCE MONITOR rm_transform_daily SET CREDIT_QUOTA = 6;
ALTER RESOURCE MONITOR rm_bi_daily SET CREDIT_QUOTA = 3;
ALTER RESOURCE MONITOR rm_ai_daily SET CREDIT_QUOTA = 4;

ALTER WAREHOUSE load_wh SET RESOURCE_MONITOR = rm_load_daily;
ALTER WAREHOUSE transform_wh SET RESOURCE_MONITOR = rm_transform_daily;
ALTER WAREHOUSE bi_wh SET RESOURCE_MONITOR = rm_bi_daily;
ALTER WAREHOUSE ai_wh SET RESOURCE_MONITOR = rm_ai_daily;

-- The trial's default warehouse: stop it after 60 idle seconds too.
ALTER WAREHOUSE IF EXISTS compute_wh SET AUTO_SUSPEND = 60;

SHOW WAREHOUSES;